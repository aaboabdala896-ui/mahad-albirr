// Service worker for معهد البر — caches the app shell so the site loads
// instantly on repeat visits and shows something even on a flaky connection.
// It intentionally does NOT cache API/data calls, since student records
// must always be fresh.

const CACHE_NAME = "mahad-albirr-shell-v1";

// Adjust this list to match your actual build output if you use a bundler
// that hashes filenames (Vite/CRA). At minimum keep the root and icons.
const APP_SHELL = [
  "/",
  "/index.html",
  "/manifest.json",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Never cache navigation/data requests aggressively — always try the
  // network first so dashboards show live data. Fall back to cache only
  // if the network is unreachable (offline).
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() => caches.match("/index.html"))
    );
    return;
  }

  // Static assets: cache-first for speed, then update cache in background.
  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response && response.status === 200) {
            caches.open(CACHE_NAME).then((cache) => cache.put(request, response.clone()));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
